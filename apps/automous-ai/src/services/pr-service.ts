import {
  createBranch,
  stageAll,
  commit,
  pushBranchWithRetry,
  hasChanges,
} from '../repo/git';
import {
  createPullRequest,
  mergePullRequest,
  getPRCheckRuns,
  getPRHeadSha,
  createIssueComment,
} from '../github/api';
import { env } from '../config/env';
import { logger } from '../utils/logger';
import type { GitHubPullRequest } from '../types/github';

// ─── Create a PR for an automated fix ────────────────────────────────────────

export async function createPullRequestForFix(
  owner: string,
  repo: string,
  repoPath: string,
  branchName: string,
  baseBranch: string,
  issueNumber: number,
  issueTitle: string,
  summary: string,
  installationId?: number,
): Promise<GitHubPullRequest> {
  createBranch(repoPath, branchName, baseBranch);

  if (!hasChanges(repoPath)) {
    throw new Error('No changes to commit — nothing was modified by the agent');
  }

  stageAll(repoPath);

  const commitMsg =
    `fix: resolve issue #${issueNumber} – ${issueTitle}\n\n` +
    `${summary}\n\n` +
    `Closes #${issueNumber}`;
  commit(repoPath, commitMsg);

  // Push with automatic rebase retry on conflict
  pushBranchWithRetry(repoPath, branchName, baseBranch);

  const prBody =
    `## Fix for Issue #${issueNumber}: ${issueTitle}\n\n` +
    `${summary}\n\n` +
    `---\n` +
    `*Automatically generated by [CodeKang](https://github.com/CodeWithJagdeep/codekang).*\n\n` +
    `Closes #${issueNumber}`;

  const pr = await createPullRequest(
    owner,
    repo,
    `fix: ${issueTitle} (#${issueNumber})`,
    prBody,
    branchName,
    baseBranch,
    installationId,
  );

  // Auto-merge if enabled and CI passes
  if (env.ENABLE_PR_AUTO_MERGE) {
    waitForCIAndMerge(
      owner,
      repo,
      pr.number,
      issueNumber,
      installationId,
    ).catch((err) => {
      logger.warn('Auto-merge failed', {
        prNumber: pr.number,
        error: (err as Error).message,
      });
    });
  }

  return pr;
}

// ─── Wait for CI checks then merge ────────────────────────────────────────────
// Polls every 30s for up to 20 minutes. Merges when all checks pass.
// Runs in the background (caller does not await).

async function waitForCIAndMerge(
  owner: string,
  repo: string,
  prNumber: number,
  issueNumber: number,
  installationId?: number,
  timeoutMs = 20 * 60 * 1000,
  pollIntervalMs = 30_000,
): Promise<void> {
  const deadline = Date.now() + timeoutMs;

  logger.info('Auto-merge: waiting for CI', { owner, repo, prNumber });

  // Give CI a moment to register checks before first poll
  await sleep(15_000);

  while (Date.now() < deadline) {
    try {
      const headSha = await getPRHeadSha(owner, repo, prNumber);
      const checks = await getPRCheckRuns(owner, repo, headSha);

      if (checks.length === 0) {
        // No checks registered yet — wait
        await sleep(pollIntervalMs);
        continue;
      }

      const allDone = checks.every((c) => c.status === 'completed');
      const allPassed = checks.every(
        (c) =>
          c.status === 'completed' &&
          (c.conclusion === 'success' ||
            c.conclusion === 'neutral' ||
            c.conclusion === 'skipped'),
      );
      const anyFailed = checks.some(
        (c) =>
          c.status === 'completed' &&
          (c.conclusion === 'failure' ||
            c.conclusion === 'timed_out' ||
            c.conclusion === 'cancelled'),
      );

      if (anyFailed) {
        logger.warn('Auto-merge cancelled: CI checks failed', {
          owner,
          repo,
          prNumber,
        });
        await createIssueComment(
          owner,
          repo,
          issueNumber,
          `## ⚠️ Auto-merge Cancelled\n\nCI checks failed on PR #${prNumber}. Please review the failures and merge manually once fixed.`,
          installationId,
        ).catch(() => {});
        return;
      }

      if (allDone && allPassed) {
        await mergePullRequest(owner, repo, prNumber, 'squash', installationId);
        logger.info('Auto-merge: PR merged successfully', {
          owner,
          repo,
          prNumber,
        });
        return;
      }

      logger.info('Auto-merge: CI still running — waiting', {
        owner,
        repo,
        prNumber,
        pending: checks
          .filter((c) => c.status !== 'completed')
          .map((c) => c.name),
      });
    } catch (err) {
      logger.warn('Auto-merge poll error', { error: (err as Error).message });
    }

    await sleep(pollIntervalMs);
  }

  logger.warn('Auto-merge: timed out waiting for CI', {
    owner,
    repo,
    prNumber,
  });
  await createIssueComment(
    owner,
    repo,
    issueNumber,
    `## ⚠️ Auto-merge Timed Out\n\nCI checks on PR #${prNumber} didn't complete within 20 minutes. Please merge manually once CI passes.`,
    installationId,
  ).catch(() => {});
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
